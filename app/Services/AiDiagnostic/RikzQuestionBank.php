    /**
     * @var array<string, array<int, array<string, mixed>>>
     */
    private array $bank = [];

    public function __construct()
    {
        $this->bank = $this->buildQuestionBank();
    }

    /**
     * @return array<string>
     */
    public function getSupportedSubjects(): array
    {
        return [
            'Математика',
            'Русский язык',
            'Белорусский язык',
            'Физика',
            'Английский язык',
        ];
    }

    /**
     * Get all questions for a subject and exam type.
     *
     * @return array<int, array<string, mixed>>
     */
    public function getQuestions(string $subject, string $examType = 'ЦТ'): array
    {
        $normalizedSubject = $this->normalizeSubject($subject);
        $questions = $this->bank[$normalizedSubject] ?? [];

        if ($questions === []) {
            return [];
        }

        return array_values(array_filter(
            $questions,
            fn (array $q): bool => in_array($q['exam_type'], ['all', $examType], true)
        ));
    }

    /**
     * Get a specific question by subject and ID.
     *
     * @return array<string, mixed>|null
     */
    public function getQuestion(string $subject, string $id): ?array
    {
        $questions = $this->getQuestions($subject);

        foreach ($questions as $question) {
            if ($question['id'] === $id) {
                return $question;
            }
        }

        return null;
    }

